import Testing
@testable import HUDCore

private func line(_ json: String) -> TranscriptEvent? { TranscriptParser.parse(line: Data(json.utf8)) }

private func prompt(_ text: String, at time: String = "2026-10-28T09:00:00.000Z", extra: String = "") -> String {
    let body = String(data: try! JSONSerialization.data(withJSONObject: text, options: .fragmentsAllowed), encoding: .utf8)!
    return #"{"type":"user",\#(extra)"timestamp":"\#(time)","message":{"role":"user","content":\#(body)}}"#
}

private func reply(_ text: String, id: String, sidechain: Bool = false) -> String {
    #"{"type":"assistant","isSidechain":\#(sidechain),"timestamp":"2026-10-28T09:01:00.000Z","message":{"id":"\#(id)","model":"claude-opus-5","content":[{"type":"text","text":"\#(text)"}]}}"#
}

private func state(_ lines: [String]) -> SessionState {
    var state = SessionState()
    for event in lines.compactMap(line) { state.apply(event) }
    return state
}

@Suite struct RecapParserTests {
    @Test func parsesTheTitlesClaudeCodeWrites() throws {
        let ai = try #require(line(#"{"type":"ai-title","aiTitle":"ESP32 WROOM-32 WiFi exploration","sessionId":"s"}"#))
        #expect(ai.role == .title)
        #expect(ai.aiTitle == "ESP32 WROOM-32 WiFi exploration")

        let named = try #require(line(#"{"type":"agent-name","agentName":"Security settings issue","sessionId":"s"}"#))
        #expect(named.role == .title)
        #expect(named.agentName == "Security settings issue")

        let custom = try #require(line(#"{"type":"custom-title","customTitle":"mine","sessionId":"s"}"#))
        #expect(custom.title == "mine")
    }

    @Test func parsesAPullRequestLink() throws {
        let event = try #require(line(#"{"type":"pr-link","prNumber":2083,"prUrl":"https://github.com/o/r/pull/2083","prRepository":"o/r"}"#))
        #expect(event.role == .link)
        #expect(event.pullRequest == PullRequestLink(url: "https://github.com/o/r/pull/2083", number: 2083, repository: "o/r"))
    }

    @Test func aPullRequestLinkWithoutAURLIsIgnored() throws {
        let event = try #require(line(#"{"type":"pr-link","prNumber":1}"#))
        #expect(event.role == .other)
        #expect(event.pullRequest == nil)
    }

    @Test func titleLinesWithMissingFieldsParseToNothing() throws {
        let event = try #require(line(#"{"type":"ai-title","sessionId":"s"}"#))
        #expect(event.role == .title)
        #expect(event.aiTitle == nil)
    }
}

@Suite struct RecapStateTests {
    @Test func keepsTheFirstAndLatestPrompts() {
        let recap = state([
            prompt("fix the retry race", at: "2026-10-28T09:00:00.000Z"),
            reply("on it", id: "m1"),
            prompt("now add a test", at: "2026-10-28T09:30:00.000Z"),
            reply("added", id: "m2"),
        ]).recap

        #expect(recap.firstPrompt?.text == "fix the retry race")
        #expect(recap.lastPrompt?.text == "now add a test")
        #expect(recap.lastPrompt?.date == TranscriptParser.parseDate("2026-10-28T09:30:00.000Z"))
        #expect(recap.lastReply?.text == "added")
    }

    @Test func aSinglePromptIsBothFirstAndLatest() {
        let recap = state([prompt("only one")]).recap
        #expect(recap.firstPrompt == recap.lastPrompt)
        #expect(recap.lastReply == nil)
    }

    @Test func injectedLinesAreNotPrompts() {
        let recap = state([
            prompt("<command-name>/clear</command-name>"),
            prompt("Caveat: the messages below were generated by the user while running local commands."),
            prompt("the real question"),
            prompt("[Request interrupted by user]"),
        ]).recap

        #expect(recap.firstPrompt?.text == "the real question")
        #expect(recap.lastPrompt?.text == "the real question")
    }

    @Test func linesClaudeCodeWroteAreNotPrompts() {
        let recap = state([
            prompt("fix the build", extra: #""origin":{"kind":"human"},"promptSource":"typed","#),
            prompt("# Update Config Skill  Modify Claude Code configuration", extra: #""isMeta":true,"#),
            prompt("Another Claude session sent a message: <agent-message>", extra: #""isMeta":true,"origin":{"kind":"peer"},"#),
            prompt("This session is being continued from a previous conversation", extra: #""isCompactSummary":true,"#),
            prompt("queued from elsewhere", extra: #""origin":{"kind":"scheduled"},"#),
        ]).recap

        #expect(recap.firstPrompt?.text == "fix the build")
        #expect(recap.lastPrompt?.text == "fix the build")
    }

    @Test func injectedLinesStillCountAsTurns() {
        // The recap skips them, but they do start work, so the turn count and flow graph still see them.
        let session = state([prompt("go"), prompt("Another Claude session sent a message", extra: #""isMeta":true,"#)])
        #expect(session.turnIndex == 2)
        #expect(session.recap.lastPrompt?.text == "go")
    }

    @Test func olderTranscriptsWithoutAnOriginStillCount() throws {
        let event = try #require(TranscriptParser.parse(line: Data(prompt("plain old prompt").utf8)))
        #expect(!event.isInjected)
    }

    @Test func subagentRepliesAreNotTheSessionsReply() {
        let recap = state([prompt("go"), reply("main answer", id: "m1"), reply("subagent chatter", id: "m2", sidechain: true)]).recap
        #expect(recap.lastReply?.text == "main answer")
    }

    @Test func longPromptsAreFlattenedAndCapped() throws {
        let long = "line one\nline two\n" + String(repeating: "x", count: 2_000)
        let note = try #require(state([prompt(long)]).recap.firstPrompt)
        #expect(!note.text.contains("\n"))
        #expect(note.text.hasPrefix("line one line two"))
        #expect(note.text.count == SessionState.noteLimit)
        #expect(note.text.hasSuffix("…"))
    }

    @Test func theUsersNameBeatsClaudeCodesTitle() {
        var recap = state([#"{"type":"ai-title","aiTitle":"Generated"}"#]).recap
        #expect(recap.headline == "Generated")

        recap = state([#"{"type":"ai-title","aiTitle":"Generated"}"#, #"{"type":"agent-name","agentName":"Renamed"}"#]).recap
        #expect(recap.headline == "Renamed")

        recap = state([#"{"type":"agent-name","agentName":"Renamed"}"#, #"{"type":"custom-title","customTitle":"Mine"}"#,
                       #"{"type":"ai-title","aiTitle":"Generated"}"#]).recap
        #expect(recap.headline == "Mine")
        #expect(recap.aiTitle == "Generated")
    }

    @Test func theLatestAITitleWins() {
        let recap = state([#"{"type":"ai-title","aiTitle":"First guess"}"#, #"{"type":"ai-title","aiTitle":"Better guess"}"#]).recap
        #expect(recap.aiTitle == "Better guess")
    }

    @Test func aTitleLineWithoutATitleKeepsThePreviousOne() {
        let recap = state([#"{"type":"ai-title","aiTitle":"Kept"}"#, #"{"type":"ai-title"}"#]).recap
        #expect(recap.aiTitle == "Kept")
    }

    @Test func pullRequestsAreListedOnceEachInOrder() {
        let a = #"{"type":"pr-link","prNumber":1,"prUrl":"https://github.com/o/r/pull/1","prRepository":"o/r"}"#
        let b = #"{"type":"pr-link","prNumber":2,"prUrl":"https://github.com/o/r/pull/2","prRepository":"o/r"}"#
        let recap = state([a, a, b, a]).recap
        #expect(recap.pullRequests.map(\.number) == [1, 2])
    }

    @Test func aSessionWithNothingInItHasAnEmptyRecap() {
        let recap = SessionState().recap
        #expect(recap == SessionRecap())
        #expect(recap.headline == nil)
    }

    @Test func recapChangesMakeSnapshotsUnequal() {
        let agent = DemoData.agents(.busy)[0]
        var renamed = agent
        renamed.recap.customTitle = "something else"
        #expect(agent != renamed)
    }
}
